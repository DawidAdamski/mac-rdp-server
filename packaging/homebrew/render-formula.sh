#!/usr/bin/env bash
# Fills the three release tokens in the formula template (F-110.6, F-110.7).
#
#   render-formula.sh 0.1.0 arm.tar.gz intel.tar.gz > mac-rdp-server.rb
#
# Kept as a script rather than a documented sed invocation so the tap copy is
# reproducible from a tag and two files, and so a forgotten sha256 fails here
# instead of in someone's `brew install`.
set -euo pipefail

if [ "$#" -ne 3 ]; then
    echo "usage: $0 VERSION ARM_TARBALL INTEL_TARBALL" >&2
    exit 64
fi

version="$1"
arm_tarball="$2"
intel_tarball="$3"
template="$(dirname "$0")/mac-rdp-server.rb"

# A leading "v" is what the tag carries and what the formula must not.
version="${version#v}"

case "$version" in
    [0-9]*.[0-9]*.[0-9]*) ;;
    *) echo "$0: '$version' is not an X.Y.Z version" >&2; exit 65 ;;
esac

for file in "$template" "$arm_tarball" "$intel_tarball"; do
    [ -f "$file" ] || { echo "$0: no such file: $file" >&2; exit 66; }
done

sha_of() { shasum -a 256 "$1" | cut -d' ' -f1; }

arm_sha="$(sha_of "$arm_tarball")"
intel_sha="$(sha_of "$intel_tarball")"

rendered="$(sed \
    -e "s|@@VERSION@@|$version|g" \
    -e "s|@@SHA256_ARM@@|$arm_sha|g" \
    -e "s|@@SHA256_INTEL@@|$intel_sha|g" \
    "$template")"

# Belt and braces: an unsubstituted token would otherwise ship to the tap and
# fail at install time, which is the one place nobody is watching.
if printf '%s' "$rendered" | grep -q '@@'; then
    echo "$0: a token was left unsubstituted:" >&2
    printf '%s' "$rendered" | grep -n '@@' >&2
    exit 70
fi

# The tap copy is generated, and whoever opens it there should know before
# they start editing it.
echo "# GENERATED by packaging/homebrew/render-formula.sh in DawidAdamski/mac-rdp-server."
echo "# Edit it there and re-render; edits made here are lost on the next release."
printf '%s\n' "$rendered"
