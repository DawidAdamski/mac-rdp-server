#!/usr/bin/env python3
"""Generates the GitHub Pages site from the Markdown already in the repository.

F-110.11 asks for one source of content, so `docs/` is not written by hand:
this turns README.md and SECURITY.md into `docs/index.md` and
`docs/security.md`. Run it after editing either document, and let CI run it
with --check so the two cannot drift apart silently.

    python3 packaging/build-docs.py           # regenerate
    python3 packaging/build-docs.py --check    # fail if out of date
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOB = "https://github.com/DawidAdamski/mac-rdp-server/blob/main"

# Relative links that work on GitHub but not on the generated site. Anything
# pointing at a file that does not become a page is sent to GitHub instead.
LINKS = {
    "(SECURITY.md)": "(security.html)",
    "(README.md)": "(index.html)",
    "(LICENSE-MIT)": f"({BLOB}/LICENSE-MIT)",
    "(LICENSE-APACHE)": f"({BLOB}/LICENSE-APACHE)",
    "(specs/)": f"({BLOB}/specs)",
    "(specs/waves.md)": f"({BLOB}/specs/waves.md)",
    "(specs/adr/)": f"({BLOB}/specs/adr)",
}

PAGES = [
    # (source, output, title)
    ("README.md", "index.md", "mac-rdp-server"),
    ("SECURITY.md", "security.md", "Security"),
]


def convert(source: str, text: str, title: str) -> str:
    """Rewrites one document into a Jekyll page."""
    for old, new in LINKS.items():
        text = text.replace(old, new)

    # GitHub's alert syntax renders as a literal "[!WARNING]" line anywhere
    # else, and the warning it carries is the one that must not be lost.
    text = text.replace("> [!WARNING]\n", "> **⚠️ Warning**\n>\n")

    # The site shows the title from the front matter, so a repeated H1 would
    # appear twice on the page.
    lines = text.splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
        while lines and not lines[0].strip():
            lines = lines[1:]
    body = "\n".join(lines).rstrip() + "\n"

    # The theme renders no navigation, so pages other than the front one carry
    # their own way back.
    if source != "README.md":
        body += "\n---\n\n[← back to the front page](index.html)\n"

    front = f"---\nlayout: default\ntitle: {title}\n---\n\n"
    generated = f"<!-- Generated by packaging/build-docs.py from {source}. Edit that file, not this one. -->\n\n"
    return front + generated + body


def render() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for source, target, title in PAGES:
        text = (ROOT / source).read_text(encoding="utf-8")
        out[ROOT / "docs" / target] = convert(source, text, title)
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    stale = []

    for path, content in render().items():
        if check:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != content:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        names = ", ".join(str(p) for p in stale)
        print(
            f"out of date: {names}\nrun `python3 packaging/build-docs.py` and commit the result",
            file=sys.stderr,
        )
        return 1
    if check:
        print("docs/ is in step with README.md and SECURITY.md")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
